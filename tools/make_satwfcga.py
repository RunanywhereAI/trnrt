    s = s.replace(KERNEL_ANCHOR, KERNEL_ANCHOR + KERNEL_HELPERS, 1)
    if s.count(DISPATCH) != 1:
        raise ValueError("the host anchor (dispatch)")
    s = s[: s.index(DISPATCH)] + HOST_HELPERS
    for gone in (
        "ncc.all_reduce(srcs=[s2src]",
        "_s2_payload(out",
        "(A * B, 2 * keep)",
        "_rows_i32(out, B, keep, RS)",
        "_attend(gv, gc, RS, table",
        "dsa_satwfc_kernel",
    ):
        if gone in s:
            raise ValueError(f"left in the copy: {gone!r}")
    if s.count("_cp_groups(world, A)") != 1:
        raise ValueError("the all_to_all keeps the row group")
    return s



def parse(spec: str) -> dict:
    """A row-class layout spec, "B:NxG+NxG..,B:.." (e.g. "24:6x24+6x8+12x4,16:4x24+12x8") -> {B: (NG per slot, ...)}, the
    classes in the order given, which must be widest first (the runner's slot order: the longest rows first). Each
    class's count is even (slots alternate between the two LNC programs, so both get the same mix) and the counts add
    up to B."""
    out = {}
    for part in filter(None, (p.strip() for p in spec.split(","))):
        b, cls = part.split(":")
        ngs = []
        for c in cls.split("+"):
            n, g = c.split("x")
            if int(n) % 2 or int(n) < 0 or int(g) < 1:
                raise ValueError(f"row classes {part!r}: {c!r} needs an even count and NG >= 1")
            ngs += [int(g)] * int(n)
        if len(ngs) != int(b):
            raise ValueError(f"row classes {part!r}: {len(ngs)} slots for B {b}")
        if ngs != sorted(ngs, reverse=True):
            raise ValueError(f"row classes {part!r}: the classes must come widest first")
        out[int(b)] = tuple(ngs)
    return out


def _rc_ints(lay: dict) -> tuple:
    """The layouts as the kernel reads them: the trn2 NKI parser takes no dict keyed by an int, so at most 2 batch sizes
    of at most 4 runs of equal NG each, as module ints (B, then (count, NG) per run, 0 where absent), rebuilt in the
    kernel by _rc_layout."""
    items = sorted(lay.items())
    out = []
    for k in range(2):
        runs = []
        if k < len(items):
            for g in items[k][1]:
                if runs and runs[-1][1] == g:
                    runs[-1][0] += 1
                else:
                    runs.append([1, g])
        if len(items) > 2 or len(runs) > 4:
            raise ValueError(f"row classes {lay}: the kernel takes at most 2 batch sizes of at most 4 runs of equal NG")
        out.append(items[k][0] if k < len(items) else 0)
        for j in range(4):
            out += runs[j] if j < len(runs) else [0, 0]
    return tuple(out)



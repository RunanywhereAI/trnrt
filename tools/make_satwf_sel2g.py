"""Generate the fused DSA layer's sel2g copies: trnrt/kernels/dsa_satwfg.py from dsa_satwf.py and dsa_satwfcg.py from
dsa_satwfc.py, each the same module with its kernel renamed (its own REV and keys) and P1, the selection, calling
dsa_sel2g._sel2g (sel2 with its compaction at any tile width, for the 3,072-page decode bucket) in place of dsa_sa._sel2
(sel2's body). Copies keep dsa_satwf(c), their REVs and every key that does not take the P3072 bucket where they are.
dsa_satwfg's COMB dispatch goes to dsa_satwfcg. tests/test_dsa_sel2g_generated.py checks both files are this transform of
the current sources, so they can't drift.
    python tools/make_satwf_sel2g.py [--check]"""

from __future__ import annotations

import os
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
K = os.path.join(HERE, "trnrt", "kernels")
P1 = "        out = _sel2(qT, wb, pkc, ppg, cand, identb, rank, keep, A, nbits2, rbits2, rev, dge, nr, qr, pf, cs)\n"
IMP = "    from .dsa_sa import _attend, _rows_i32, _sel2, _snd_write\n"
SH_IMP = "from . import shell as SH\n"
# (P1's replacement, the kernel-block import added, the module import added, the REV term, the docstring's body)
VARIANT = (
    (
        "        out = _sel2g(qT, wb, pkc, ppg, cand, identb, rank, keep, A, nbits2, rbits2, rev, dge, nr, qr, pf, cs,\n"
        "                     0)  # sel2g's body: any tile width (GENERATED: tools/make_satwf_sel2g.py)\n"
    ),
    "    from .dsa_sel2g import _sel2g\n",
    "from . import dsa_sel2g as _SLG\n",
    " ^ _SLG.REVG)",
    "dsa_sel2g._sel2g (sel2 with\nits compaction at any tile width: the P3072 bucket) in place of dsa_sa._sel2; routed by dsa_satwf.SEL2G",
)
# name: (source, copy, kernel, copy's kernel, the REV line's tail, other replacements)
FILES = {
    "satwfg": (
        "dsa_satwf.py",
        "dsa_satwfg.py",
        "dsa_satwf_kernel",
        "dsa_satwfg_kernel",
        "^ SAT.REV ^ CW.REV ^ FS.REV)",
        [("    from . import dsa_satwfc\n", "    from . import dsa_satwfcg as dsa_satwfc\n")],
    ),
    "satwfcg": (
        "dsa_satwfc.py",
        "dsa_satwfcg.py",
        "dsa_satwfc_kernel",
        "dsa_satwfcg_kernel",
        "^ SATWF.REV ^ MS.REV_K)",
        [],
    ),
}
CUT = "\n\n# The P3072 decode page bucket (SEL2G;"  # dsa_satwf's own dispatch to the copy: never in a copy


def _once(s: str, a: str, b: str) -> str:
    if s.count(a) != 1:
        raise ValueError(f"expected once: {a[:70]!r} ({s.count(a)})")
    return s.replace(a, b)


def transform(name: str, src: str) -> str:
    f, _, kern, kern_g, rev_tail, more = FILES[name]
    p1, imp, mimp, rev_term, doc = VARIANT
    if CUT in src:
        src = src[: src.index(CUT)] + "\n"
    out = _once(src, P1, p1)
    out = _once(out, IMP, IMP + imp)
    out = _once(out, SH_IMP, SH_IMP + mimp)
    out = _once(out, rev_tail, rev_tail[:-1] + rev_term)
    for a, b in more:
        out = _once(out, a, b)
    if kern_g in out:
        raise ValueError(f"{kern_g} already in {f}")
    out = out.replace(kern, kern_g)
    head = (
        f'"""GENERATED by tools/make_satwf_sel2g.py from {f}: its kernel renamed {kern_g} and P1 calling {doc} '
        "(dsa_satwf.py's dispatch). Do not edit.\n\n"
    )
    if not out.startswith('"""'):
        raise ValueError(f"{f} has no module docstring")
    return head + out[3:]


def paths(name: str) -> tuple[str, str]:
    return os.path.join(K, FILES[name][0]), os.path.join(K, FILES[name][1])


if __name__ == "__main__":
    bad = 0
    for name in FILES:
        src, dst = paths(name)
        with open(src) as f:
            want = transform(name, f.read())
        if "--check" in sys.argv:
            ok = False
            if os.path.exists(dst):
                with open(dst) as f:
                    ok = f.read() == want
            print(FILES[name][1], "matches" if ok else "STALE")
            bad += not ok
        else:
            with open(dst, "w") as f:
                f.write(want)
            print("wrote", dst)
    sys.exit(1 if bad else 0)
